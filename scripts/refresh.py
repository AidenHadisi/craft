#!/usr/bin/env python3
"""Build Craft's host adapters and refresh available local installations."""

import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import tomllib

ROOT = Path(__file__).resolve().parents[1]
PLUGIN = "craft@craft-local"
READ_ONLY = "This is a read-only agent. Do not edit files or perform actions that change external state.\n\n"


def json_text(value):
    return json.dumps(value, ensure_ascii=False, indent=2) + "\n"


def read_agent(path):
    """Source agents intentionally use a small, dependency-free metadata format."""
    text = path.read_text()
    if not text.startswith("---\n") or "\n---\n" not in text[4:]:
        raise ValueError(f"Missing agent frontmatter: {path}")
    front, body = text[4:].split("\n---\n", 1)
    meta = {}
    for line in front.splitlines():
        key, sep, value = line.partition(":")
        value = value.strip()
        if not sep or key not in {"name", "description", "model", "readonly"} or key in meta:
            raise ValueError(f"Unsupported agent metadata in {path}: {line}")
        if value.startswith('"'):
            value = json.loads(value)
        if not isinstance(value, str) or not value or value in {">", ">-", "|", "|-"}:
            raise ValueError(f"Use a single-line string for {key} in {path}")
        meta[key] = value
    if meta.get("name") != path.stem or not re.fullmatch(r"craft-[a-z0-9-]+", path.stem):
        raise ValueError(f"Agent name must match its craft-* filename: {path}")
    if not meta.get("description") or not body.strip():
        raise ValueError(f"Missing description or instructions: {path}")
    if meta.get("model", "inherit") != "inherit":
        raise ValueError(f"Shared agents inherit the host model: {path}")
    if meta.get("readonly", "false") not in {"true", "false"}:
        raise ValueError(f"Invalid readonly value: {path}")
    instructions = body.strip() + "\n"
    if meta.get("readonly") == "true":
        instructions = READ_ONLY + instructions
    return meta, instructions


def expected_files(root):
    metadata = json.loads((root / ".cursor-plugin/plugin.json").read_text())
    if metadata["name"] != "craft":
        raise ValueError("The refresh script manages only Craft")
    # A skill's supporting files must travel with that skill.
    for skill in sorted((root / "skills").iterdir()):
        if not skill.is_dir():
            continue
        for document in skill.rglob("*.md"):
            for link in re.findall(r"\]\(([^)]+)\)", document.read_text()):
                target = link.split("#", 1)[0]
                if not target or re.match(r"[a-zA-Z][a-zA-Z0-9+.-]*:", target):
                    continue
                resolved = (document.parent / target).resolve()
                if not resolved.is_relative_to(skill.resolve()) or not resolved.exists():
                    raise ValueError(f"Skill reference must exist inside {skill}: {document}: {link}")
    files = {}
    for host in ("codex", "claude"):
        for path in sorted((root / "skills").rglob("*")):
            if path.is_file():
                files[Path(host) / path.relative_to(root)] = path.read_bytes()
        files[Path(host) / "LICENSE"] = (root / "LICENSE").read_bytes()
        manifest = dict(metadata)
        if host == "codex":
            manifest["skills"] = "./skills/"
        files[Path(host) / f".{host}-plugin/plugin.json"] = json_text(manifest).encode()
    for path in sorted((root / "agents").glob("*.md")):
        meta, instructions = read_agent(path)
        values = {"name": meta["name"], "description": meta["description"],
                  "developer_instructions": instructions}
        toml = "# Generated by Craft; edit the source agents/*.md instead.\n"
        toml += "\n".join(f"{key} = {json.dumps(value, ensure_ascii=False)}" for key, value in values.items()) + "\n"
        tomllib.loads(toml)
        files[Path("codex-agents") / f"{path.stem}.toml"] = toml.encode()
        files[Path("codex/agents") / path.name] = path.read_bytes()
        front = {"name": meta["name"], "description": meta["description"], "model": "inherit"}
        if meta.get("readonly") == "true":
            front["disallowedTools"] = "Write, Edit, NotebookEdit"
        markdown = "---\n" + "\n".join(f"{key}: {json.dumps(value, ensure_ascii=False)}" for key, value in front.items())
        files[Path("claude/agents") / path.name] = (markdown + "\n---\n\n" + instructions).encode()
    return files


def build(root, check=False):
    files = expected_files(root)
    generated = root / ".generated"
    if generated.is_symlink():
        raise ValueError(f"Refusing to replace a symlink: {generated}")
    actual = {p.relative_to(generated): p.read_bytes() for p in generated.rglob("*") if p.is_file()}
    if check:
        if actual != files:
            raise ValueError("Generated files are stale; run scripts/refresh.py --build-only")
        return
    if actual == files:
        return
    with tempfile.TemporaryDirectory(prefix=".craft-build-", dir=root) as temp:
        stage = Path(temp) / "new"
        stage.mkdir()
        for relative, content in files.items():
            target = stage / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content)
        previous = Path(temp) / "previous"
        if generated.exists():
            generated.rename(previous)
        try:
            stage.rename(generated)
        except OSError:
            if previous.exists():
                previous.rename(generated)
            raise


def agent_links(root, codex_home, install=False):
    """Validate every destination before changing any personal agent files."""
    pairs = [(p, codex_home / "agents" / p.name)
             for p in sorted((root / ".generated/codex-agents").glob("*.toml"))]
    for source, target in pairs:
        if target.is_symlink():
            if target.resolve() != source.resolve():
                raise ValueError(f"Agent link belongs to another source: {target}")
        elif target.exists():
            if not target.is_file() or tomllib.loads(target.read_text()) != tomllib.loads(source.read_text()):
                raise ValueError(f"Preserving a different agent file; reconcile it before refreshing: {target}")
    if install:
        (codex_home / "agents").mkdir(parents=True, exist_ok=True)
        for source, target in pairs:
            if target.is_symlink():
                continue
            if target.exists():
                target.unlink()  # Identical generated data, checked above.
            target.symlink_to(source.resolve())


def run(*args, capture=False):
    result = subprocess.run(args, check=True, text=True, stdout=subprocess.PIPE if capture else None)
    return json.loads(result.stdout) if capture else None


def install_codex(root):
    codex_home = Path(os.environ.get("CODEX_HOME", str(Path.home() / ".codex"))).expanduser()
    agent_links(root, codex_home)
    entries = run("codex", "plugin", "marketplace", "list", "--json", capture=True)["marketplaces"]
    previous = next((e for e in entries if e["name"] == "craft-local"), None)
    if previous and Path(previous["root"]).resolve() != root.resolve():
        source = previous.get("marketplaceSource", {})
        if source.get("sourceType") != "local":
            raise ValueError("craft-local already uses a non-local source; preserving it")
        run("codex", "plugin", "marketplace", "remove", "craft-local")
        try:
            run("codex", "plugin", "marketplace", "add", str(root))
        except subprocess.CalledProcessError:
            run("codex", "plugin", "marketplace", "add", source["source"])
            raise
    elif previous is None:
        run("codex", "plugin", "marketplace", "add", str(root))
    run("codex", "plugin", "add", PLUGIN)
    agent_links(root, codex_home, install=True)


def install_claude(root):
    run("claude", "plugin", "validate", str(root / ".generated/claude"))
    entries = run("claude", "plugin", "marketplace", "list", "--json", capture=True)
    previous = next((e for e in entries if e["name"] == "craft-local"), None)
    if previous and (previous.get("source") != "directory" or Path(previous["path"]).resolve() != root.resolve()):
        raise ValueError("Claude's craft-local marketplace points elsewhere; preserving it")
    if previous is None:
        run("claude", "plugin", "marketplace", "add", str(root), "--scope", "user")
    run("claude", "plugin", "install", PLUGIN, "--scope", "user")
    run("claude", "plugin", "update", PLUGIN, "--scope", "user")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--build-only", action="store_true")
    mode.add_argument("--check", action="store_true")
    parser.add_argument("--target", choices=("all", "codex", "claude"), default="all")
    args = parser.parse_args()
    build(ROOT, check=args.check)
    print("Craft generated files verified." if args.check else "Craft packages are current.", flush=True)
    if args.build_only or args.check:
        return
    for host, install in (("codex", install_codex), ("claude", install_claude)):
        if args.target not in ("all", host):
            continue
        if not shutil.which(host):
            print(f"{host}: CLI not found; package prepared, installation skipped.", flush=True)
            continue
        install(ROOT)
        print(f"{host}: refreshed from {ROOT}", flush=True)
    print("Reload Cursor and start new sessions to load changes.")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        raise SystemExit(f"Craft refresh failed: {error}")
